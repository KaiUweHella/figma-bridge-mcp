// Cross-check the response signature against the OS: is the PID listening on
// `port` the one in our PID file? Returns true/false, or null when unknown
// (lsof/netstat unavailable, no PID file, unparsable output).
function pidFileOwnsPort(port) {
  try {
    const filePid = parseInt(readFileSync(PID_FILE, 'utf8').trim(), 10);
    if (!Number.isInteger(filePid)) return null;
    const raw = getPortPid(port);
    if (!raw) return null;
    // lsof -ti may list several PIDs (listener + connected clients).
    const pids = String(raw).split('\n').map((s) => parseInt(s.trim(), 10));
    if (!pids.some(Number.isInteger)) return null;
    return pids.includes(filePid);
  } catch {
    return null;
  }
}

// Probe whether the process holding `port` is one of our daemons — WITHOUT
// sending the session token (a foreign squatter on the port must never see
// it). Two signals: (1) our daemon answers unauthenticated /health with 403
// and a JSON `error` starting with "Unauthorized"; (2) the listening PID
// matches our PID file. Since the port fallback exists, a squatter MIMICKING
// the 403 shape would otherwise not be benign — it would make this daemon
// exit "already running" and silently deny the whole toolchain. The PID
// cross-check demotes a mimic to a plain foreign squatter (→ fallback);
// when the PID cannot be determined, the signature alone decides.
async function looksLikeOurDaemon(port) {
  try {
    // 800ms: a legitimate daemon with a briefly busy event loop must not be
    // misclassified as foreign — that would spawn a second daemon on the
    // next port (the exact split-brain this probe exists to prevent).
    const res = await fetch(`http://127.0.0.1:${port}/health`, {
      signal: AbortSignal.timeout(800),
    });
    if (res.status !== 403) return false;
    const body = await res.json();
    if (typeof body.error !== 'string' || !body.error.startsWith('Unauthorized')) return false;
    return pidFileOwnsPort(port) !== false;
  } catch {
    return false;
  }
}

function listenOn(server, port, host) {
  return new Promise((resolve, reject) => {
    const onError = (err) => reject(err);
    server.once('error', onError);
    server.listen(port, host, () => {
      server.removeListener('error', onError);
      resolve();
    });
  });
}

function closeListener(server) {
  return new Promise((resolve) => {
    if (!server.listening) return resolve();
    server.close(() => resolve());
  });
}

async function tryListen(port) {
  await listenOn(httpServer, port, '127.0.0.1');
  try {
    await listenOn(ipv6HttpServer, port, '::1');
  } catch (error) {
    await closeListener(httpServer);
    throw error;
  }
}

async function start() {
  // Split-brain guard: an existing daemon may sit on a LATER range port (its
  // start-time squatter since gone). Binding 3456 now would give two daemons,
  // with the plugin scan connecting to whichever answers first. Scan the whole
  // range for one of ours before binding anything. Skipped for an explicit
  // DAEMON_PORT — the singleton check below covers the single candidate.
  if (PORT_CANDIDATES.length > 1) {
    for (const port of PORT_CANDIDATES) {
      if (await looksLikeOurDaemon(port)) {
        console.log(`[daemon] Already running on port ${port} — exiting (singleton).`);
        process.exit(0);
      }
    }
  }

  for (const port of PORT_CANDIDATES) {
    try {
      await tryListen(port);
      boundPort = port;
      break;
    } catch (err) {
      if (err && err.code === 'EADDRINUSE') {
        if (await looksLikeOurDaemon(port)) {
          console.log(`[daemon] Port ${port} already owned by another daemon — exiting (singleton).`);
          process.exit(0);
        }
        console.log(`[daemon] Port ${port} held by a foreign process — trying next.`);
        continue;
      }
      console.error('[daemon] server error:', err);
      process.exit(1);
    }
  }

  if (boundPort === null) {
    console.error(
      `[daemon] All ports ${PORT_CANDIDATES.join(', ')} are busy. ` +
      `Free one of them or set DAEMON_PORT (note: the Figma plugin can only reach 3456-3460).`
    );
    process.exit(1);
  }

  try { writeFileSync(PID_FILE, String(process.pid)); } catch {}
  writePortFile(boundPort);
  console.log(`[daemon] figma-bridge-mcp daemon running on port ${boundPort} (pid ${process.pid})`);
  console.log(`[daemon] Mode: plugin (Safe Mode only)`);
  console.log(`[daemon] Idle timeout: ${IDLE_TIMEOUT_MS / 1000}s`);
  console.log(`[daemon] Auth: HTTP token + plugin access key required`);
}

// Unexpected errors after a successful bind (the pre-bind path handles its own).
for (const server of [httpServer, ipv6HttpServer]) {
  server.on('error', (err) => {
    if (boundPort === null) return; // tryListen owns pre-bind errors
    console.error('[daemon] server error:', err);
    process.exit(1);
  });
}

start();

// Graceful shutdown
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);

// Drain window for in-flight /exec responses on shutdown. A long render can
// exceed this — the cap keeps `daemon restart` snappy; only shutdowns during
// an active eval wait at all.
const SHUTDOWN_DRAIN_MS = 10000;
let shuttingDown = false;

function shutdown() {
  if (shuttingDown) return;
  shuttingDown = true;
  console.log('[daemon] Shutting down...');
  if (idleTimer) clearTimeout(idleTimer);
  // Stop accepting new connections; established in-flight responses live on.
  httpServer.close(() => {});
  ipv6HttpServer.close(() => {});
  // Keep the plugin socket OPEN until in-flight evals have answered — closing
  // it first reset every running /exec with a connection error even though the
  // code kept executing in Figma (duplicate-mutation bait on manual restart).
  const deadline = Date.now() + SHUTDOWN_DRAIN_MS;
  const finish = () => {
    if (inFlightExecs > 0) {
      console.log(`[daemon] Forcing exit with ${inFlightExecs} eval(s) still in flight`);
    }
    for (const [ws] of conns) { try { ws.close(); } catch {} }
    // Only clear the port file if it still names our port — a dying old daemon
    // must not delete a newer daemon's published port.
    if (boundPort !== null) clearPortFile(process.env, boundPort);
    process.exit(0);
  };
  const tick = () => {
    if (inFlightExecs === 0 || Date.now() >= deadline) return finish();
    setTimeout(tick, 200);
  };
  tick();
}
